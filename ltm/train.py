"""Pretrain LTM on synthetic tables from the SCM prior (batched, GPU-ready).

    python -m ltm.train --steps 20000 --workers 2 --out ltm_v1.pt

Every step trains on a batch of same-shape tables. Tables are generated by
background workers so the GPU is not left waiting. A resume file (<out>.state) is
written next to the weights, so an interrupted run continues with --resume.
"""
import argparse
import os
import time
import warnings

import numpy as np
import torch
from torch.utils.data import DataLoader, IterableDataset, get_worker_info

from .model import LTM, episode_loss
from .prior import generate_table


def _shape(rng, max_rows, max_feats):
    n_rows = int(np.exp(rng.uniform(np.log(50), np.log(max_rows))))
    n_feats = int(np.exp(rng.uniform(np.log(2), np.log(max_feats))))
    task = "classification" if rng.random() < 0.6 else "regression"
    return n_rows, n_feats, task


def _tensors(t, perm):
    X = torch.tensor(t.X[perm], dtype=torch.float32)
    y = torch.tensor(t.y[perm], dtype=torch.long if t.task == "classification" else torch.float32)
    return X, torch.tensor(t.cat_mask), y


def make_episode(rng, max_rows, max_feats):
    """One table (used for evaluation)."""
    n_rows, n_feats, task = _shape(rng, max_rows, max_feats)
    t = generate_table(rng, n_rows, n_feats, task)
    X, cm, y = _tensors(t, rng.permutation(n_rows))
    return X, cm, y, max(10, int(0.7 * n_rows)), task, t.n_classes


def make_batch(rng, batch, max_rows, max_feats):
    """A batch of tables that share rows, features and task."""
    n_rows, n_feats, task = _shape(rng, max_rows, max_feats)
    n_ctx = max(10, int(0.7 * n_rows))
    Xs, cms, ys, ks = [], [], [], []
    for _ in range(batch):
        t = generate_table(rng, n_rows, n_feats, task)
        X, cm, y = _tensors(t, rng.permutation(n_rows))
        Xs.append(X); cms.append(cm); ys.append(y); ks.append(t.n_classes)
    k = torch.tensor(ks, dtype=torch.long) if task == "classification" else None
    return torch.stack(Xs), torch.stack(cms), torch.stack(ys), n_ctx, task, k


class Episodes(IterableDataset):
    def __init__(self, seed, batch, max_rows, max_feats):
        self.seed, self.batch, self.max_rows, self.max_feats = seed, batch, max_rows, max_feats

    def __iter__(self):
        w = get_worker_info()
        rng = np.random.default_rng([self.seed, w.id if w else 0])
        while True:
            yield make_batch(rng, self.batch, self.max_rows, self.max_feats)


@torch.no_grad()
def evaluate(model, device, n_tables=30, seed=12345, max_rows=300, max_feats=20):
    """Compare LTM with HistGradientBoosting on fresh prior tables."""
    from sklearn.ensemble import HistGradientBoostingClassifier as C
    from sklearn.ensemble import HistGradientBoostingRegressor as R
    from sklearn.metrics import accuracy_score, r2_score
    rng = np.random.default_rng(seed)
    model.eval()
    res = {"classification": ([], []), "regression": ([], [])}
    maj = []
    for _ in range(n_tables):
        X, cm, y, n_ctx, task, k = make_episode(rng, max_rows, max_feats)
        Xn, yn = X.numpy(), y.numpy()
        if task == "classification" and len(np.unique(yn[:n_ctx])) < 2:
            continue
        out = model(X.to(device), cm.to(device), y[:n_ctx].to(device), task, k).cpu()
        gb = (C() if task == "classification" else R()).fit(Xn[:n_ctx], yn[:n_ctx])
        if task == "classification":
            res[task][0].append(accuracy_score(yn[n_ctx:], out.argmax(1).numpy()))
            res[task][1].append(accuracy_score(yn[n_ctx:], gb.predict(Xn[n_ctx:])))
            maj.append(accuracy_score(yn[n_ctx:], np.full(len(yn) - n_ctx, np.bincount(yn[:n_ctx]).argmax())))
        else:
            ym, ys = yn[:n_ctx].mean(), max(yn[:n_ctx].std(), 1e-6)
            res[task][0].append(r2_score(yn[n_ctx:], out.numpy() * ys + ym))
            res[task][1].append(r2_score(yn[n_ctx:], gb.predict(Xn[n_ctx:])))
    model.train()
    for task, (a, b) in res.items():
        metric = "accuracy" if task == "classification" else "R2"
        extra = f" | majority class {np.mean(maj):.3f}" if task == "classification" else ""
        print(f"  {task:14s} {metric}: LTM {np.mean(a):.3f} | HistGB {np.mean(b):.3f}{extra} (n={len(a)})", flush=True)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--steps", type=int, default=20000)
    p.add_argument("--batch", type=int, default=8)
    p.add_argument("--lr", type=float, default=3e-4)
    p.add_argument("--d", type=int, default=128)
    p.add_argument("--layers", type=int, default=6)
    p.add_argument("--max_rows", type=int, default=600)
    p.add_argument("--max_feats", type=int, default=40)
    p.add_argument("--workers", type=int, default=0)
    p.add_argument("--eval_every", type=int, default=1000)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", default="ltm_v1.pt")
    p.add_argument("--resume", action="store_true")
    a = p.parse_args()

    device = "cuda" if torch.cuda.is_available() else "cpu"
    state_path = a.out + ".state"
    start, opt_state = 1, None
    if a.resume and os.path.exists(a.out) and os.path.exists(state_path):
        ck = torch.load(a.out, map_location="cpu")
        st = torch.load(state_path, map_location="cpu")
        a.d, a.layers, start, opt_state = ck["d"], ck["layers"], st["step"] + 1, st["opt"]

    torch.manual_seed(a.seed)
    model = LTM(d=a.d, layers=a.layers).to(device)
    opt = torch.optim.AdamW(model.parameters(), lr=a.lr, weight_decay=0.01)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, a.lr, total_steps=a.steps, pct_start=0.03)
    if opt_state is not None:
        model.load_state_dict(ck["model"])
        opt.load_state_dict(opt_state)
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            for _ in range(start - 1):
                sched.step()
        print(f"resumed from step {start - 1}")
    print(f"device: {device} | params: {sum(p.numel() for p in model.parameters()) / 1e6:.2f}M", flush=True)

    ds = Episodes(a.seed + start, a.batch, a.max_rows, a.max_feats)
    loader = DataLoader(ds, batch_size=None, num_workers=a.workers,
                        prefetch_factor=4 if a.workers > 0 else None)
    it = iter(loader)

    hist = {"classification": [], "regression": []}
    t0 = time.time()
    for step in range(start, a.steps + 1):
        X, cm, y, n_ctx, task, k = next(it)
        X, cm, y = X.to(device), cm.to(device), y.to(device)
        if k is not None:
            k = k.to(device)
        loss, _ = episode_loss(model, X, cm, y, n_ctx, task, k)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step(); sched.step(); opt.zero_grad()
        hist[task].append(loss.item())
        if step % 100 == 0:
            c = np.mean(hist["classification"][-100:]) if hist["classification"] else float("nan")
            r = np.mean(hist["regression"][-100:]) if hist["regression"] else float("nan")
            print(f"step {step} | cls loss {c:.3f} | reg mse {r:.3f} (1.0 = predict mean) | {time.time() - t0:.0f}s", flush=True)
        if step % a.eval_every == 0 or step == a.steps:
            torch.save({"model": model.state_dict(), "d": a.d, "layers": a.layers}, a.out)
            torch.save({"opt": opt.state_dict(), "step": step}, state_path)
            evaluate(model, device, max_rows=a.max_rows, max_feats=a.max_feats)


if __name__ == "__main__":
    main()
